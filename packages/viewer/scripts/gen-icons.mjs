// Writes src/ui/components/icon-paths.generated.ts: the path of each icon in icon-names.ts, outlined and filled, from
// @material-symbols/svg-400 (Rounded, weight 400; Apache-2.0). Run with `pnpm --filter @wordedits/viewer icons`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const rounded = join(dirname(require.resolve('@material-symbols/svg-400/package.json')), 'rounded');
const namesFile = readFileSync(join(here, '../src/ui/components/icon-names.ts'), 'utf8');
const list = /ICONS = \[([\s\S]*?)\] as const/.exec(namesFile)?.[1];
if (!list) throw new Error('No ICONS array in icon-names.ts');
const names = [...list.matchAll(/'([a-z0-9_]+)'/g)].map((m) => m[1]);

const pathOf = (file) => {
  const svg = readFileSync(join(rounded, file), 'utf8');
  if (!/viewBox="0 -960 960 960"/.test(svg)) throw new Error(`${file}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
  if (paths.length === 0 || /<(?!svg|path|\/svg)[a-z]/.test(svg)) throw new Error(`${file}: not a plain path icon`);
  return paths.join(' ');
};

const lines = names.map((n) => `  ${n}: { outline: '${pathOf(`${n}.svg`)}', fill: '${pathOf(`${n}-fill.svg`)}' },`);
writeFileSync(
  join(here, '../src/ui/components/icon-paths.generated.ts'),
  `// SPDX-License-Identifier: MIT
// Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (Apache-2.0; Rounded, weight 400). Do not edit.
// viewBox "0 -960 960 960".
import type { IconName } from './icon-names.js';

export const ICON_PATHS: Record<IconName, { outline: string; fill: string }> = {
${lines.join('\n')}
};
`,
);
console.log(`${names.length} icons written`);
